const fs = require("fs");
const path = require("path");
const { THRESHOLD } = require("./score");
const CORPUS_LOCALES = require("../corpus/build").LOCALES;

const ROOT = path.resolve(__dirname, "../..");
const RESULTS = path.join(ROOT, "bench/results");
const START = "<!-- bench:languages:start -->";
const END = "<!-- bench:languages:end -->";
const SUMMARY_COLUMNS = ["locale", "engine", "gated", "images", "errors", "checks", "correct", "check_accuracy", "fit_images",
  "fit_read", "fit_recall", "cer", "trunc_tp", "trunc_fp", "trunc_fn", "trunc_tn", "trunc_precision", "trunc_recall",
  "median_ms", "conf_fit", "conf_clip"];
const ROW_COLUMNS = ["image", "case", "present", "absent", "truncated", "cer", "read"];

const cell = (v) => {
  const s = v === null || v === undefined ? "" : String(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const line = (cols, obj) => cols.map((c) => cell(obj[c])).join(",");

/** Splits one CSV line (RFC 4180 quoting). */
function split(l) {
  const out = [];
  let cur = "", q = false;
  for (let i = 0; i < l.length; i++) {
    const c = l[i];
    if (q) {
      if (c === '"' && l[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') q = false; else cur += c;
    } else if (c === '"') q = true;
    else if (c === ",") { out.push(cur); cur = ""; } else cur += c;
  }
  out.push(cur);
  return out;
}
function value(s) {
  if (s === "") return null;
  if (s === "true" || s === "false") return s === "true";
  return /^-?\d+(\.\d+)?$/.test(s) ? Number(s) : s;
}
const record = (cols, l) => Object.fromEntries(split(l).map((v, i) => [cols[i], value(v)]));

/** The header row every CSV starts with: catscan version, macOS build and Vision revision (spec 05 Results). */
const stamp = (t) => `# catscan=${t.catscan} macos=${t.macos} macos_build=${t.macos_build} vision_revision=${t.vision_revision}`;

/** One language: the stamp, its summary row, then one row per image wrong in any metric. */
function languageCsv(t, summary, rows) {
  return [stamp(t), SUMMARY_COLUMNS.join(","), line(SUMMARY_COLUMNS, summary), ROW_COLUMNS.join(","),
    ...rows.map((r) => line(ROW_COLUMNS, r))].join("\n") + "\n";
}
function readLanguageCsv(file) {
  const ls = fs.readFileSync(file, "utf8").split("\n").filter((l) => l !== "");
  return { stamp: ls[0], summary: record(SUMMARY_COLUMNS, ls[2]), rows: ls.slice(4).map((l) => record(ROW_COLUMNS, l)) };
}
const summaryCsv = (t, summaries) => [stamp(t), SUMMARY_COLUMNS.join(","), ...summaries.map((s) => line(SUMMARY_COLUMNS, s))].join("\n") + "\n";
function readSummaryCsv(file) {
  const ls = fs.readFileSync(file, "utf8").split("\n").filter((l) => l !== "");
  return { stamp: ls[0], summaries: ls.slice(2).map((l) => record(SUMMARY_COLUMNS, l)) };
}

/**
 * Rebuilds the summaries of a folder from its language CSVs (spec 05 D12): only CSVs whose stamp equals `t`'s are
 * used, in `order`; the others are returned as `stale`.
 */
function collect(dir, t, order) {
  const want = stamp(t);
  const summaries = [], stale = [];
  for (const l of order) {
    const f = path.join(dir, `${l}.csv`);
    if (!fs.existsSync(f)) continue;
    const c = readLanguageCsv(f);
    if (c.stamp === want) summaries.push(c.summary);
    else stale.push(`${l}.csv (${c.stamp.slice(2)})`);
  }
  return { summaries, stale };
}

const fmt = (v, d = 2) => (v === null || v === undefined ? "-" : Number(v).toFixed(d));
function verdict(s) {
  if (s.gated) return s.check_accuracy !== null && s.check_accuracy >= THRESHOLD ? "pass" : "fail";
  return s.check_accuracy !== null && s.check_accuracy >= THRESHOLD ? "informational" : "partial";
}

/** Corpus provenance: one ICU for older records, ICU groups since TODO-037. */
const corpusLine = (c) => (c.groups && c.groups.length > 1
  ? `${c.groups.map((g) => `ICU ${g.icu}, CLDR ${g.cldr} (${g.locales.join(", ")})`).join("; ")}; seed ${c.seed}`
  : `ICU ${c.groups ? c.groups[0].icu : c.icu}, CLDR ${c.groups ? c.groups[0].cldr : c.cldr}, seed ${c.seed}`);

/** The Languages section for every macOS folder that holds a full run (summary.csv and meta.json). */
function section(results = RESULTS, coverage = []) {
  const out = [START, "## Languages", "",
    "Generated by `npm run bench:table` from `bench/results/`; do not edit by hand. Synthetic images drawn by Core Text in the macOS system UI font, not device screenshots: 60 CLDR strings per language (`bench/corpus/`, Unicode License v3) x 3 cases (fit, ellipsis, clip) x 3 sizes x 2 themes x 2 backgrounds, the image being the text's box. Check accuracy counts one `present` check per fit image and one `absent` check (another string of the language) per image, so three of every four checks are `absent` and fit recall is the stricter reading number; CER is the best-match character error rate on fit images in grapheme clusters; truncation is `catscan truncated` without boxes over all three cases. Gate: >= 98% check accuracy for the locales in `bench/languages/plan.js` `GATED` (en, the 12 study locales, el, he, bg, and later sv, da, no, nb, fi, nl, ar and the European locales that passed); another language below 98% is listed as partial.", ...(coverage.length ? ["", ...coverage] : [])];
  const dirs = fs.existsSync(results) ? fs.readdirSync(results).filter((d) => fs.existsSync(path.join(results, d, "summary.csv"))
    && fs.existsSync(path.join(results, d, "meta.json"))).sort() : [];
  if (!dirs.length) out.push("", "No full run is recorded yet.");
  for (const d of dirs) {
    const { summaries } = readSummaryCsv(path.join(results, d, "summary.csv"));
    const m = JSON.parse(fs.readFileSync(path.join(results, d, "meta.json"), "utf8"));
    out.push("", `### macOS ${d}`, "",
      "| Language | Engine | Check accuracy | Fit recall | CER | Truncation precision / recall | ms per image | Gate |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |");
    for (const s of summaries) {
      out.push(`| ${s.locale} | ${s.engine} | ${fmt(s.check_accuracy)}% | ${fmt(s.fit_recall, 3)} | ${fmt(s.cer, 3)} | ${fmt(s.trunc_precision, 3)} / ${fmt(s.trunc_recall, 3)} | ${fmt(s.median_ms, 0)} | ${verdict(s)} |`);
    }
    const t = m.tools;
    out.push("",
      `- Setup: ${m.machine}, ${t.chip}, macOS ${t.macos} (${t.macos_build}), Vision revision ${t.vision_revision}, Node ${t.node}, ${t.swift}, ${t.tesseract} with ${t.leptonica}; ${m.date}. Raw numbers: \`bench/results/${d}/\`.`,
      // TODO-042 D4: the top-level timing is the last run's; a folder assembled from several runs lists each.
      (m.runs || []).length > 1 ? `- Timing: ${m.runs.map((r, i) => `run ${i + 1}, ${r.timing || "timing unknown"}`).join("; ")}.` : `- Timing: ${m.timing}.`,
      ...((m.runs || []).length > 1 ? [`- Assembled from ${m.runs.length} runs: ${m.runs.map((r) => `${r.locales.join(", ")} on ${r.date}`).join("; ")}.`] : []),
      `- Corpus: ${corpusLine(m.corpus)}.`);
  }
  out.push("", "- Rerun (full, about 1.5 h on an M5): `npm run bench -- --record`, then `npm run bench:table`.",
    "- Rerun (quick, a few minutes, compared with the recorded quick run): `npm run bench -- --quick`.",
    "- Prerequisites: Xcode, `npm ci`, `npm run build`, and Homebrew `tesseract` with `tesseract-lang` for the fallback rows (the run checks them first and names the install command).",
    END);
  return out.join("\n");
}

/** A setup error the user fixes by hand: exit 2 with the file and the fix (spec 11 D12). */
const fix = (msg) => Object.assign(new Error(msg), { exit: 2 });

/** Replaces the text between the markers; throws (exit 2) when a marker is missing. */
function rewrite(doc, body, start = START, end = END, name = "docs/BENCHMARKS.md") {
  const a = doc.indexOf(start), b = doc.indexOf(end);
  if (a < 0 || b < a) throw fix(`${name} has no ${start} ... ${end} markers; add both where the generated block goes`);
  return doc.slice(0, a) + body + doc.slice(b + end.length);
}

// Spec 11: the README table. Reproducible rows come from the folder bench/reference.json names (D2), aggregated per
// engine (D3); study rows come from bench/study.json and link to the Study section of docs/BENCHMARKS.md (D4).
const R_START = "<!-- bench:start -->";
const R_END = "<!-- bench:end -->";
const ENGINES = [["Vision", (e) => e.startsWith("vision")], ["Tesseract fallback", (e) => e.startsWith("tesseract")]];

function median(xs) {
  const s = xs.filter((x) => typeof x === "number").sort((a, b) => a - b);
  if (!s.length) return null;
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}
const lowest = (ss, k) => ss.filter((s) => typeof s[k] === "number").reduce((lo, s) => (!lo || s[k] < lo[k] ? s : lo), null);
const ratio = (a, b) => (a + b ? a / (a + b) : null);

/** Per-engine aggregates of a summary.csv (spec 11 Rows). */
function aggregate(summaries) {
  return ENGINES.map(([label, is]) => {
    const ss = summaries.filter((s) => is(String(s.engine)));
    if (!ss.length) return null;
    const tot = (k) => ss.reduce((n, s) => n + (s[k] || 0), 0);
    return {
      label, count: ss.length, low: lowest(ss, "check_accuracy"), median: median(ss.map((s) => s.check_accuracy)),
      lowFit: lowest(ss, "fit_recall"), cer: median(ss.map((s) => s.cer)),
      precision: ratio(tot("trunc_tp"), tot("trunc_fp")), recall: ratio(tot("trunc_tp"), tot("trunc_fn")),
      ms: median(ss.map((s) => s.median_ms)),
    };
  }).filter(Boolean);
}

/** Spec 05 D8 / spec 11 D5: a record taken with simulators or emulators running is shown as such. */
// Anything else is not called idle: a missing or unknown note must not publish an idle measurement.
const timingMode = (timing) => (/^under load/.test(timing || "") ? "under load" : /^no simulator or emulator running/.test(timing || "") ? "idle" : "timing unknown");
/** TODO-042 D4: idle only when every run of every folder was idle; meta.timing alone is the last run's. */
function foldTiming(metas) {
  // A run without its own timing is unknown, never the last run's mode.
  const modes = metas.flatMap((m) => ((m.runs || []).length ? m.runs.map((r) => r.timing) : [m.timing])).map(timingMode);
  return modes.includes("under load") ? "under load" : modes.every((x) => x === "idle") ? "idle" : "timing unknown";
}

/** GitHub heading anchors of a Markdown file (lowercase, punctuation dropped, spaces to hyphens, -1 for repeats). */
function anchors(md) {
  const seen = new Map(), out = new Set();
  let fence = false;
  for (const l of md.split("\n")) {
    if (/^\s*```/.test(l)) fence = !fence;
    const h = !fence && /^#{1,6}\s+(.+?)\s*#*\s*$/.exec(l);
    if (!h) continue;
    const base = h[1].replace(/<[^>]+>/g, "").toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, "").trim().replace(/\s/g, "-");
    const n = seen.get(base) || 0;
    seen.set(base, n + 1);
    out.add(n ? `${base}-${n}` : base);
  }
  return out;
}

const pct = (v) => (v === null ? "-" : `${fmt(v)}%`);

function readJson(root, rel) {
  const f = path.join(root, rel);
  if (!fs.existsSync(f)) throw fix(`${rel} is missing; restore it from git`);
  try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch (e) { throw fix(`${rel} is not valid JSON: ${e.message}`); }
}

const PARTS = ["languages", "power", "llm"];
/** The folders `languages` names: a string, or a list whose later folders win per locale (TODO-042 D5). */
const folderList = (v) => (v === null ? [] : Array.isArray(v) ? v : [v]);

/**
 * bench/reference.json and bench/study.json, validated, with the languages folders read and merged per locale
 * (spec 11 D2, TODO-042 D5): `lang` is null when `languages` is null.
 */
function reference(root) {
  const ref = readJson(root, "bench/reference.json");
  const study = readJson(root, "bench/study.json");
  // A typo must not turn into an empty table that bench:check then accepts.
  const okLang = (v) => v === null || typeof v === "string" || (Array.isArray(v) && v.length > 0 && v.every((x) => typeof x === "string") && new Set(v).size === v.length);
  if (!ref || typeof ref !== "object" || PARTS.some((p) => !(p in ref)) || !okLang(ref.languages) || PARTS.slice(1).some((p) => ref[p] !== null && typeof ref[p] !== "string")) {
    throw fix(`bench/reference.json must name ${PARTS.join(", ")}, each a results folder name or null (languages may be a list of distinct folder names)`);
  }
  if (!Array.isArray(study.rows) || typeof study.measured_on !== "string") throw fix("bench/study.json needs a measured_on string and a rows array");
  for (const s of study.rows) {
    const miss = ["metric", "engine", "value", "date", "anchor"].filter((k) => typeof s?.[k] !== "string" || !s[k]);
    if (miss.length) throw fix(`bench/study.json row ${JSON.stringify(s?.metric ?? s)} lacks ${miss.join(", ")}`);
    if (s.part !== undefined && !PARTS.includes(s.part)) throw fix(`bench/study.json row "${s.metric}" has part "${s.part}"; use one of ${PARTS.join(", ")}`);
  }
  for (const part of PARTS) {
    for (const folder of folderList(ref[part])) {
      if (part !== "languages") throw fix(`bench/reference.json sets "${part}", whose rows this catscan does not generate yet; set it to null`);
      const d = path.join(root, "bench/results", folder);
      if (!["summary.csv", "meta.json"].every((f) => fs.existsSync(path.join(d, f)))) {
        throw fix(`bench/reference.json names "${folder}" for ${part}, but bench/results/${folder}/ has no summary.csv and meta.json; record it with \`npm run bench -- --record\` or fix the entry`);
      }
    }
  }
  if (ref.languages === null) return { ref, study, lang: null };
  const folders = folderList(ref.languages).map((name) => {
    const d = path.join(root, "bench/results", name);
    const m = JSON.parse(fs.readFileSync(path.join(d, "meta.json"), "utf8"));
    const sumFile = path.join(d, "summary.csv");
    const sum = readSummaryCsv(sumFile);
    // summary.csv and meta.json are written separately: both must come from the same run, and the columns must be
    // the ones this reader maps by position. Folders may differ from each other (TODO-042: 27.2 and 27.2.1).
    const rel = `bench/results/${name}`;
    if (sum.stamp !== stamp(m.tools || {})) throw fix(`${rel}/summary.csv (${sum.stamp.slice(2)}) and meta.json (${stamp(m.tools || {}).slice(2)}) are from different runs; record the folder again`);
    if (fs.readFileSync(sumFile, "utf8").split("\n")[1] !== SUMMARY_COLUMNS.join(",")) throw fix(`${rel}/summary.csv has other columns than this catscan writes; record the folder again`);
    return { name, meta: m, summaries: sum.summaries };
  });
  const byLocale = new Map(), superseded = [];
  for (const f of folders) {
    for (const s of f.summaries) {
      const prev = byLocale.get(s.locale);
      if (prev) superseded.push({ locale: s.locale, from: prev.folder.name, to: f.name });
      byLocale.set(s.locale, { s, folder: f });
    }
  }
  return { ref, study, lang: { folders, merged: [...byLocale.values()], superseded } };
}

const ENGINE_SHORT = (e) => (String(e).startsWith("tesseract") ? "Tesseract" : "Vision");

/**
 * TODO-042 D2/D6: the coverage lines written into both the README block and the BENCHMARKS Languages section, so the
 * counts and partials quoted anywhere come from the records and bench:check catches drift.
 */
function coverage(lang) {
  if (!lang) return [];
  const groups = ENGINES.map(([label, is]) => [label, lang.merged.filter((x) => is(String(x.s.engine))).map((x) => x.s.locale).sort()]).filter(([, ls]) => ls.length);
  const below = lang.merged.filter((x) => !(typeof x.s.check_accuracy === "number" && x.s.check_accuracy >= THRESHOLD))
    .sort((a, b) => (a.s.check_accuracy ?? -1) - (b.s.check_accuracy ?? -1));
  const pairs = new Map();
  for (const x of lang.superseded) {
    const k = `\`${x.to}\` over \`${x.from}\``;
    pairs.set(k, [...(pairs.get(k) || []), x.locale]);
  }
  return [`**Coverage** (generated): ${lang.merged.length} locales recorded, every number measured on synthetic images drawn by Core Text, not on device screenshots. ${groups.map(([label, ls]) => `${label} (${ls.length}): ${ls.join(", ")}`).join(". ")}.`,
    "",
    `**Under the ${THRESHOLD}% gate:** ${below.length ? below.map((x) => `${x.s.locale} ${pct(x.s.check_accuracy)} (${ENGINE_SHORT(x.s.engine)}, ${verdict(x.s)})`).join(", ") : "none"}. Every other locale measures at or above ${THRESHOLD}% check accuracy.`,
    ...(pairs.size ? ["", `**Recorded twice, the later record counts:** ${[...pairs].map(([k, ls]) => `${ls.join(", ")} (${k})`).join("; ")}.`] : [])];
}

/** The README block between the bench markers (spec 11). `root` holds bench/ and docs/; `doc` is BENCHMARKS.md. */
function readmeBlock(root, doc) {
  const { ref, study, lang } = reference(root);
  const heads = anchors(doc);
  if (!heads.has("languages")) throw fix("docs/BENCHMARKS.md has no \"Languages\" heading, which the README links to; restore it");
  const rows = [];
  if (lang) {
    const lo = (r, k, d) => (r ? `${k === "check_accuracy" ? pct(r[k]) : fmt(r[k], d)} (${r.locale})` : "-");
    for (const a of aggregate(lang.merged.map((x) => x.s))) {
      // Each engine names only the setups and runs its locales came from.
      const used = lang.folders.filter((f) => lang.merged.some((x) => x.folder === f && ENGINES.find(([l]) => l === a.label)[1](String(x.s.engine))));
      const on = used.map((f) => `${f.meta.tools.chip}, macOS ${f.meta.tools.macos} (${f.meta.tools.macos_build}), ${f.meta.date}`).join("; ");
      const e = `${a.label} (${a.count} locale${a.count === 1 ? "" : "s"})`;
      rows.push([`Check accuracy, median / lowest`, e, `${pct(a.median)} / ${lo(a.low, "check_accuracy")}`],
        [`Fit recall, lowest`, e, lo(a.lowFit, "fit_recall", 3)],
        [`CER, median`, e, fmt(a.cer, 3)],
        [`Truncation precision / recall, pooled`, e, `${fmt(a.precision, 3)} / ${fmt(a.recall, 3)}`],
        [`Median ms per image`, e, `${fmt(a.ms, 0)} (${foldTiming(used.map((f) => f.meta))})`]);
      for (const r of rows.slice(-5)) r.push("reproducible", on);
    }
  }
  // TODO-046: the element-box overlap row, from the held-out half of the DOM set (results/overlap-elements.json).
  const elFile = path.join(root, "results/overlap-elements.json");
  if (fs.existsSync(elFile)) {
    const o = readJson(root, "results/overlap-elements.json");
    if (!heads.has("overlap-from-element-boxes")) throw fix("docs/BENCHMARKS.md has no \"Overlap from element boxes\" heading, which the README links to; restore it");
    const tt = o.held_out["text-text"], tg = o.held_out["text-graphic"];
    rows.push([`Overlap with element boxes (\`--boxes\`), precision / recall, overlaps of ${o.gate_bars.minPx} px and more: text over text; text over an icon or image`,
      `Vision (${o.locales.length} languages)`, `${fmt(tt.precision, 3)} / ${fmt(tt.recall, 3)}; ${fmt(tg.precision, 3)} / ${fmt(tg.recall, 3)}`,
      "[reproducible](docs/BENCHMARKS.md#overlap-from-element-boxes)", `${o.tools.chip}, macOS ${o.tools.macos} (${o.tools.macos_build}), ${o.date}`]);
  }
  // Spec 12: the overlap row, from the held-out half of the synthetic set (results/overlap.json, bench/overlap.js).
  const ovFile = path.join(root, "results/overlap.json");
  if (fs.existsSync(ovFile)) {
    const o = readJson(root, "results/overlap.json");
    if (!heads.has("overlap-without-boxes")) throw fix("docs/BENCHMARKS.md has no \"Overlap without boxes\" heading, which the README links to; restore it");
    const h = o.held_out;
    rows.push([`Overlap without boxes (OCR only), precision / recall, overlaps of ${o.gate.minAmount} px and more${h.gate_pass ? "" : " (experimental: under the gate)"}`,
      `Vision (${o.locales.length} languages)`, `${fmt(h.precision, 3)} / ${fmt(h.recall, 3)}`,
      "[reproducible](docs/BENCHMARKS.md#overlap-without-boxes)", `${o.chip}, macOS ${o.macos} (${o.macos_build}), ${o.date}`]);
  }
  for (const s of study.rows) {
    if (s.part && ref[s.part]) continue; // the part is reproducible now; its rows come from the referenced run
    if (!heads.has(s.anchor)) throw fix(`bench/study.json row "${s.metric}" links to #${s.anchor}, which is not a heading in docs/BENCHMARKS.md; add the heading or fix the anchor`);
    rows.push([s.metric, s.engine, !s.unit ? s.value : s.unit === "%" ? `${s.value}%` : `${s.value} ${s.unit}`, `[study](docs/BENCHMARKS.md#${s.anchor})`, `${study.measured_on}, ${s.date}`]);
  }
  const where = lang ? lang.folders.map((f) => `\`bench/results/${f.name}/\``).join(" and ") + (lang.folders.length > 1 ? " (the later folder's record per locale)" : "") : null;
  return [R_START,
    `Generated by \`npm run bench:table\`; do not edit by hand. **reproducible** rows come from the public synthetic benchmark${where ? ` in ${where}` : ""}, which anyone can rerun on an Apple-silicon Mac; per-language numbers are in [\`docs/BENCHMARKS.md\`](docs/BENCHMARKS.md#languages). **study** rows are quoted from the dated feasibility study over private screenshots, which cannot be published or rerun.`,
    "",
    "| Metric | Engine | Value | Source | Measured on |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.join(" | ")} |`),
    ...(lang ? ["", ...coverage(lang)] : []),
    "",
    "- Rerun (full, about 1.5 h on an M5): `npm run bench -- --record`, then `npm run bench:table`. Timing depends on the chip and load; the summary prints your numbers next to the reference run.",
    "- Rerun (quick, a few minutes, compared with the recorded quick run): `npm run bench -- --quick`.",
    "- Check that this table matches the committed results (Node only): `npm run bench:check`.",
    R_END].join("\n");
}

/** Both generated files in memory (spec 11 D1): [{ name, file, old, next }]. */
function build(root = ROOT, locales = CORPUS_LOCALES) {
  const docFile = path.join(root, "docs/BENCHMARKS.md"), readmeFile = path.join(root, "README.md");
  for (const [f, n] of [[docFile, "docs/BENCHMARKS.md"], [readmeFile, "README.md"]]) if (!fs.existsSync(f)) throw fix(`${n} is missing; restore it from git`);
  const { ref, lang } = reference(root);
  // TODO-042 D3: every corpus locale has a record in the reference folders, so the table cannot silently shrink.
  const missing = lang ? locales.filter((l) => !lang.merged.some((x) => x.s.locale === l)) : [];
  if (missing.length) {
    throw fix(`bench/reference.json "languages" (${folderList(ref.languages).join(", ")}) has no record for ${missing.join(", ")}; record them with \`npm run bench -- --record --lang ${missing.join(",")}\` and add that folder to the list`);
  }
  const doc = fs.readFileSync(docFile, "utf8");
  const nextDoc = rewrite(doc, section(path.join(root, "bench/results"), coverage(lang)));
  const readme = fs.readFileSync(readmeFile, "utf8");
  const nextReadme = rewrite(readme, readmeBlock(root, nextDoc), R_START, R_END, "README.md");
  return [{ name: "README.md", file: readmeFile, old: readme, next: nextReadme, markers: [R_START, R_END] },
    { name: "docs/BENCHMARKS.md", file: docFile, old: doc, next: nextDoc, markers: [START, END] }];
}

const block = (text, [a, b]) => { const i = text.indexOf(a), j = text.indexOf(b); return i < 0 || j < i ? [] : text.slice(i, j + b.length).split("\n"); };

/** A line diff (LCS) of two blocks: "-" committed, "+" generated. */
function diff(a, b) {
  const n = a.length, m = b.length, L = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) L[i][j] = a[i] === b[j] ? L[i + 1][j + 1] + 1 : Math.max(L[i + 1][j], L[i][j + 1]);
  const out = [];
  let i = 0, j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && a[i] === b[j]) { i++; j++; } else if (i < n && (j === m || L[i + 1][j] >= L[i][j + 1])) out.push(`- ${a[i++]}`);
    else out.push(`+ ${b[j++]}`);
  }
  return out;
}

/** npm run bench:table (write) and npm run bench:check (--check). Returns the exit code; logs through `log`/`err`. */
function main(argv, { root = ROOT, log = console.log, err = console.error, locales = CORPUS_LOCALES } = {}) {
  const checkOnly = argv.includes("--check");
  const name = checkOnly ? "bench:check" : "bench:table";
  let files;
  try { files = build(root, locales); } catch (e) { err(`${name}: ${e.message}`); return e.exit || 5; }
  if (!checkOnly) {
    for (const f of files) {
      if (f.next === f.old) log(`${f.name}: unchanged`);
      else { fs.writeFileSync(f.file, f.next); log(`${f.name}: rewrote the generated block`); }
    }
    return 0;
  }
  const bad = files.filter((f) => f.next !== f.old);
  for (const f of bad) err(`${name}: ${f.name} differs from the committed results:\n${diff(block(f.old, f.markers), block(f.next, f.markers)).join("\n")}`);
  if (bad.length) { err("run npm run bench:table and commit the result"); return 1; }
  log(`${name}: README.md and docs/BENCHMARKS.md match the committed results`);
  return 0;
}

