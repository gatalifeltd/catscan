// Value: protects=the before/after delta tells a catscan change from an unchanged finding and ties each new kind
// to its behavior-change bullet; fails_when=a reworded finding counts as gone plus new, a kind named by a bullet in
// the range is unexplained, a bullet outside the range explains it, or two schemas are compared;
// why_new=new script; seam=none; no_claim=that the before and after runs used the same screenshots.
const results = (schema, rows) => ({ results_schema: schema, results: rows });
const row = (screen, findings, checks = []) => ({ command: 'check', device: 'iPhone', text_size: 'L', locale: 'de', screen, findings, checks });
test('finding-delta: unchanged, changed one to one, gone plus new, failed checks, and explained_by from the range', () => {
  const before = temp('before-');
  const afterDir = temp('after-');
  write(before, { 'a.json': results(4, [row('home', [{ kind: 'truncated', line: 'Weiter  zum' }, { kind: 'overlap', line: 'A' }, { kind: 'overlap', line: 'B' }]), row('cart', [{ kind: 'untranslated', line: 'Buy' }])]) });
  write(afterDir, { 'a.json': results(4, [row('home', [{ kind: 'truncated', line: 'weiter zum' }, { kind: 'overlap', line: 'C' }, { kind: 'overlap', line: 'D' }, { kind: 'wrong-language', reason: 'mixed', line: 'Hallo' }], [{ kind: 'text', verdict: 'fail', text: 'Pay' }]), row('cart', [{ kind: 'untranslated', line: 'Buy now' }])]) });
  const changes = { releases: [
    { version: '0.61.0', changes: [{ id: 'check-text-fail', kind: 'exit-code', text: 'a missing `text` check fails' }] },
    { version: '0.59.0', changes: [{ id: 'wrong-language-mixed', kind: 'default-on', text: 'flags mixed lines' }] },
  ] };
  writeFileSync(join(before, 'changes.json'), JSON.stringify(changes));
  const r = run('finding-delta.mjs', [before, afterDir, '--changes', join(before, 'changes.json'), '--from', OLD, '--to', NEW]);
  assert.equal(r.status, 0, r.stderr);
  const d = JSON.parse(r.stdout);
  assert.deepEqual(d.counts, { new: 4, gone: 2, changed: 1, unchanged: 1, unexplained: 4 - 1 + 1 });
  assert.deepEqual(d.changed.map((c) => [c.kind, c.from, c.to]), [['untranslated', 'buy', 'buy now']]);
  assert.deepEqual(d.new.find((f) => f.kind === 'wrong-language:mixed').explained_by, { version: '0.59.0', id: 'wrong-language-mixed', kind: 'default-on' });
  assert.equal(d.new.find((f) => f.kind === 'check:text').explained_by, null, 'a bullet after the target does not explain it');
  assert.equal(explain('check:text', changes, OLD, '0.61.0').id, 'check-text-fail');
  // A bullet at the current version is already in effect, and a non-behavior kind explains nothing.
  assert.equal(explain('wrong-language:mixed', changes, '0.59.0', NEW), null);
  assert.equal(explain('x', { releases: [{ version: NEW, changes: [{ id: 'x', kind: 'protocol', text: '' }] }] }, OLD, NEW), null);
  // Whole words only: a bare kind is not explained by an id that merely starts with it, nor a check by a text id.
  const near = { releases: [{ version: NEW, changes: [{ id: 'overlap-sheets', kind: 'default-on', text: 'sheets' }, { id: 'overlap-stacked-text', kind: 'default-on', text: 'x' }] }] };
  assert.equal(explain('overlap', near, OLD, NEW), null);
  assert.equal(explain('check:text', near, OLD, NEW), null);
  assert.equal(explain('overlap:sheets', near, OLD, NEW).id, 'overlap-sheets');
  // A downgrade reads the same range.
  assert.equal(explain('wrong-language:mixed', changes, NEW, OLD).id, 'wrong-language-mixed');
});

