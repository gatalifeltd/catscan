// Value: protects=the plan lists every behavior change between two versions, read from the published package,
// and a registry failure stops with nothing changed; fails_when=the range is off by one at either end, a downgrade
// reads the older file, an opt-out already passed is missed, or an unknown version does not exit 2;
// why_new=new script; seam=a local fake registry stands in for npm; no_claim=the real registry's availability.
const CHANGES = { schema: 1, releases: [
  { version: '0.60.0', changes: [{ id: 'fail-on-skip', kind: 'exit-code', text: '`check` now fails on a skipped screen', opt_out: '`--allow-skip`' }] },
  { version: '0.59.0', changes: [{ id: 'doctor-update', kind: 'output', text: '`doctor` prints an update line', opt_out: '`--offline`' }] },
  { version: '0.58.0', changes: [{ id: 'old', kind: 'output', text: 'older', opt_out: 'none' }] },
] };
test('behavior-range: range bounds, downgrade marks undone, annotate names commands and opt-outs', () => {
  assert.deepEqual(range(CHANGES, OLD, NEW).map((c) => c.id), ['doctor-update', 'fail-on-skip']);
  assert.deepEqual(range(CHANGES, NEW, OLD).map((c) => c.id), ['doctor-update', 'fail-on-skip']);
  const surfaces = { invocations: [{ argv: ['catscan', 'check', 'shots', '--allow-skip'] }, { argv: ['catscan', 'doctor', '--offline=true'] }] };
  assert.deepEqual(annotate(range(CHANGES, OLD, NEW), surfaces).map((c) => [c.id, c.commands_named, c.opted_out]),
    [['doctor-update', ['doctor'], true], ['fail-on-skip', ['check'], true]]);
  assert.equal(annotate(range(CHANGES, OLD, NEW), { invocations: [{ argv: ['catscan', 'check'] }] })[1].opted_out, false);
  // A negated opt-out ("leave out `--known`") is taken by NOT passing the flag; each named invocation counts.
  const negated = [{ version: NEW, id: 'known-gate', kind: 'exit-code', text: '`check --known` fails on a new finding', opt_out: 'leave out `--known`' }];
  const two = { invocations: [{ file: 'ci.yml', line: 3, argv: ['catscan', 'check', '--known', 'k.json'] }, { file: 'ci.yml', line: 9, argv: ['catscan', 'check', 'shots'] }] };
  assert.deepEqual(annotate(negated, two).map((c) => [c.opted_out, c.hits]), [['partial', [{ file: 'ci.yml', line: 3 }]]]);
  assert.equal(annotate(negated, { invocations: [two.invocations[1]] })[0].opted_out, true);
  // One opt-out can offer both kinds: "leave the page out ..., or list its id in `--allow`" adds `--allow`.
  const mixed = [{ version: NEW, id: 'overlap-sheets', kind: 'default-on', text: '`overlap --boxes` reports sheets',
    opt_out: 'leave the hidden page out of the boxes file, or list its id or text in `--allow`' }];
  const runs = { invocations: [{ file: 'a', line: 1, argv: ['pnpm', 'dlx', '@catscan/cli@1.0.0', 'overlap', '--boxes', 'b.json', '--allow', 'x'] },
    { file: 'a', line: 2, argv: ['npx', '-p', '@catscan/cli', 'catscan', 'overlap', '--boxes', 'b.json'] }] };
  assert.deepEqual(annotate(mixed, runs).map((c) => [c.commands_named, c.opted_out, c.hits]), [[['overlap'], 'partial', [{ file: 'a', line: 2 }]]]);
  // An opt-out of `none` cannot be taken: every named invocation is hit.
  assert.equal(annotate([{ ...negated[0], opt_out: 'none' }], two)[0].opted_out, false);
});

const BARE = '0.35.0';
async function fakeRegistry() {
  const dir = temp('registry-');
  const pkg = join(dir, 'package');
  write(pkg, { 'package.json': { name: '@catscan/core-js', version: NEW }, 'behavior-changes.json': CHANGES });
  const tgz = join(dir, `core-js-${NEW}.tgz`);
  assert.equal(spawnSync('tar', ['-czf', tgz, '-C', dir, 'package']).status, 0);
  // BARE: an older core-js that ships no behavior-changes.json.
  const bare = join(dir, 'bare');
  write(join(bare, 'package'), { 'package.json': { name: '@catscan/core-js', version: BARE } });
  const bareTgz = join(dir, `core-js-${BARE}.tgz`);
  assert.equal(spawnSync('tar', ['-czf', bareTgz, '-C', bare, 'package']).status, 0);
  const tarballs = { [NEW]: readFileSync(tgz), [BARE]: readFileSync(bareTgz) };
  const server = createServer((req, res) => {
    const base = `http://127.0.0.1:${server.address().port}`;
    const t = req.url.match(/-(\d+\.\d+\.\d+)\.tgz$/);
    if (t) { res.writeHead(200, { 'content-type': 'application/octet-stream' }); res.end(tarballs[t[1]]); return; }
    if (!/core-js$/i.test(decodeURIComponent(req.url))) { res.writeHead(404); res.end('{}'); return; }
    const versions = Object.fromEntries(Object.entries(tarballs).map(([v, bytes]) => [v, { name: '@catscan/core-js', version: v,
      dist: { tarball: `${base}/@catscan/core-js/-/core-js-${v}.tgz`, shasum: createHash('sha1').update(bytes).digest('hex'),
        integrity: `sha512-${createHash('sha512').update(bytes).digest('base64')}` } }]));
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ name: '@catscan/core-js', 'dist-tags': { latest: NEW }, versions }));
  });
  await new Promise((ok) => server.listen(0, '127.0.0.1', ok));
  after(() => server.close());
  return `http://127.0.0.1:${server.address().port}/`;
}

