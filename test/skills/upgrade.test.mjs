// Value: protects=the default target (npm latest) never plans an unnamed downgrade; fails_when=a project pinned above
// --to gets edits or commands without --allow-downgrade, direction ignores a lockfile-only or skewed pin, or the
// skill's own version or a user-scope MCP pin decides it; why_new=npm latest (0.0.4) sat below every product release
// and the default plan downgraded; seam=findSurfaces, CLI; no_claim=registry lookups (TODO-103 U1, D1, D2, D6).
test('find-surfaces --to: a target below the project pins is a downgrade that plans nothing unless allowed', () => {
  const pinned = (v, extra = {}) => repo({ 'package.json': { name: 'app', devDependencies: { '@catscan/cli': v } },
    'package-lock.json': { lockfileVersion: 3, packages: { '': {}, 'node_modules/@catscan/cli': { version: v } } }, ...extra });
  const down = findSurfaces(pinned('0.68.8'), { to: '0.0.4', home: home() });
  assert.equal(down.direction, 'downgrade');
  assert.equal(down.direction_from, '0.68.8');
  assert.deepEqual([down.edits, down.commands], [[], []]);
  assert.match(down.stop, /0\.0\.4 is older than 0\.68\.8/);
  assert.doesNotMatch(down.stop, /try:|--allow-downgrade/);
  const allowed = findSurfaces(pinned('0.68.8'), { to: '0.0.4', home: home(), allowDowngrade: true });
  assert.equal(allowed.direction, 'downgrade');
  assert.ok(allowed.edits.length > 0 && allowed.commands.length > 0);
  assert.equal(allowed.stop, undefined);
  assert.equal(findSurfaces(pinned('0.60.0'), { to: '0.68.8', home: home() }).direction, 'upgrade');
  assert.equal(findSurfaces(pinned('0.68.8'), { to: '0.68.8', home: home() }).direction, 'none');
  // A release is newer than its prerelease.
  assert.equal(findSurfaces(pinned('1.0.0-rc.1'), { to: '1.0.0', home: home() }).direction, 'upgrade');
  assert.equal(findSurfaces(pinned('1.0.0'), { to: '1.0.0-rc.1', home: home() }).direction, 'downgrade');
  // No exact pin: nothing to compare.
  assert.equal(findSurfaces(repo({ 'package.json': { name: 'app', devDependencies: { '@catscan/cli': '^0.60.0' } } }), { to: '0.0.4', home: home() }).direction, null);
  // Skew: the newest pin decides.
  const skew = findSurfaces(repo({ 'package.json': { name: 'app', devDependencies: { '@catscan/cli': '0.60.0' } },
    '.github/workflows/ui.yml': 'jobs:\n  ui:\n    steps:\n      - run: npx -y @catscan/cli@0.70.0 check shots\n' }), { to: '0.65.0', home: home() });
  assert.deepEqual([skew.direction, skew.direction_from, skew.edits.length], ['downgrade', '0.70.0', 0]);
  // A ranged manifest with only the lockfile pinned still counts.
  const lockOnly = findSurfaces(repo({ 'package.json': { name: 'app', devDependencies: { '@catscan/cli': '^0.68.0' } },
    'package-lock.json': { lockfileVersion: 3, packages: { '': {}, 'node_modules/@catscan/cli': { version: '0.68.8' } } } }), { to: '0.0.4', home: home() });
  assert.deepEqual([lockOnly.direction, lockOnly.direction_from], ['downgrade', '0.68.8']);
  // A user-scope MCP pin (home() pins 0.58.0) and the skill's own version never decide it.
  assert.equal(findSurfaces(pinned('0.50.0'), { to: '0.55.0', home: home() }).direction, 'upgrade');
  // CLI: exit 0 with the stop line; --allow-downgrade without --to is a usage error.
  const root = pinned('0.68.8');
  const cli = run('find-surfaces.mjs', [root, '--to', '0.0.4'], { env: { ...process.env, HOME: home() } });
  assert.equal(cli.status, 0, cli.stderr);
  assert.equal(JSON.parse(cli.stdout).direction, 'downgrade');
  const bad = run('find-surfaces.mjs', [root, '--allow-downgrade']);
  assert.equal(bad.status, 2);
  assert.match(bad.stderr, /--allow-downgrade/);
});

