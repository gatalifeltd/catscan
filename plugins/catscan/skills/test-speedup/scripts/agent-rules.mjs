// agent-rules v1 (catscan test-speedup skill). Node built-ins only. Installs the test-writing rules
// so an agent that never loads the skill still follows them: one invariant line in the always-loaded agent
// instructions (AGENTS.md, and CLAUDE.md when it exists and does not import @AGENTS.md) that points to the
// rules section of the project's testing doc (default docs/testing.md), which this script also writes.
// Always-loaded text stays one line. With --gpu it also writes the GPU rule as its own marked block,
// so an upgrade can find and refresh it; an unmarked copy of the published text is replaced, any other wording is
// reported for a hand edit. This file is the only copy of these texts.
import { existsSync, mkdirSync, readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const VERSION = 1;
export const LINE_MARK = '<!-- test-speedup:testing-rules -->';
export const START = '<!-- test-speedup:testing-rules start (generated by agent-rules.mjs; edit there, not here) -->';
export const END = '<!-- test-speedup:testing-rules end -->';
export const GPU_START = '<!-- test-speedup:gpu-rule start (generated by agent-rules.mjs; edit there, not here) -->';
export const GPU_END = '<!-- test-speedup:gpu-rule end -->';

const USAGE = `Usage: node agent-rules.mjs [--root DIR] [--doc PATH] [--gpu --gpu-helper NAME --gpu-guard CMD] [--check]
Writes one testing-rules line into DIR/AGENTS.md, and into DIR/CLAUDE.md when it exists and does not import
@AGENTS.md, and the rules section into DIR/<doc> (default docs/testing.md, created when missing). --gpu also
writes the GPU rule block into the same instruction files, naming the launch helper and the guard command; an
unmarked copy of the published rule is replaced, other wording is reported. A second run changes nothing.
--check writes nothing and exits 1 when a line, section or block is missing or stale.
Exit 0 ok, 1 check failed, 2 usage error or no instructions file (ask the owner).`;

export function line(doc) {
  return `- Testing: before writing or changing a test, read the rules in \`${doc}\` (lowest layer, no duplicate claims; assert once, the assertion budget fails a test over 1000 \`expect\` calls; never wait in a \`pgrep\` or \`ps | grep\` loop). ${LINE_MARK}\n`;
}

export function block() {
  return [
    START,
    '## Testing rules',
    '',
    '- Lowest layer that can prove the claim: unit, then web e2e, then device. Before adding a test, search the lower layers for the same claim (the event, state or text name) and extend that test instead of adding a duplicate.',
    '- A loop over many cases asserts once: push each failure into an array and `expect(failures).toEqual([])` after the loop; inside a `waitFor` or retry callback, throw instead of calling `expect` and assert once after the wait. Every Jest and Vitest config loads the test-speedup assertion budget, which fails a test over 1000 `expect` calls; there is no per-test opt-out. Jest `test.concurrent` and the global `expect` in a Vitest concurrent test (`test.concurrent`, `describe.concurrent`, `sequence.concurrent`) escape it, so keep loops out of those tests.',
    '- Wait on state (a lock, a file, an exit code, a completion notification), never on time, and never in a loop over `pgrep` or `ps | grep`: the pattern matches the loop itself, and a `grep` that succeeds on empty input never ends it.',
    '- Changed-only selection fails closed: a path the rules do not place runs the full suite. Ship metadata (`VERSION`, `CHANGELOG.md`, a `package.json` or lockfile change in the root `version` only) selects nothing.',
    '- Long specs start first, in their own project. Device runs go through the launcher, which takes the device-set lock and queues in arrival order; never boot a device by hand.',
    '- Timeouts are hang guards, not speed budgets. Raising one, skipping or deleting a test needs the owner.',
    END,
  ].join('\n') + '\n';
}

// The GPU rule as guards.md published it before the block existed; an unmarked copy of exactly this is replaced.
export function gpuText(helper, guard) {
  return `GPU in every test: every config, spec and script that renders or boots a device starts on the host GPU where one exists, from its first line, through \`${helper}\`. Browsers (Chromium, Electron): \`--use-angle=metal\` on macOS; with no host GPU (a Linux runner, a VM) they fall back to SwiftShader and the renderer smoke spec warns instead of failing. Emulators: \`-gpu host\`; on macOS a CPU renderer works and is only a per-run opt-out; on a GPU-less Linux cloud VM use a GPU VM or another slot (CPU renderers crashed in a tested GCP setup). The CPU is never a default where a GPU exists; GPU-less CI sets the documented opt-out \`E2E_GPU=swiftshader\` on a line with the owner's \`gpu-launch: <why>\` comment. \`${guard}\` fails on a launch site that bypasses it.`;
}

export function gpuBlock(helper, guard) {
  return `${GPU_START}\n- ${gpuText(helper, guard)}\n${GPU_END}\n`;
}

// Writes the marked GPU block. An unmarked copy of the published text (any line wrapping, optional quotes or
// list marker) becomes the block; an unmarked rule in other words is the owner's to merge, so it throws.
export function applyGpu(text, wanted, published) {
  if (text.includes(GPU_START) || text.includes(GPU_END)) return applyBlock(text, wanted, GPU_START, GPU_END, 'test-speedup GPU marker');
  const words = published.split(/\s+/).map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  const copy = new RegExp(`^[ \\t]*(?:[-*]|\\d+\\.)?[ \\t]*["\u201c]?${words.join('\\s+')}["\u201d]?[ \\t]*(?:\\n|$)`, 'm').exec(text);
  if (copy) return text.slice(0, copy.index) + wanted + text.slice(copy.index + copy[0].length);
  const other = text.search(/GPU in every test/);
  if (other !== -1) throw new Error(`line ${lineOf(text, other)} holds a GPU rule in other words. Fix: merge it into the block by hand (node agent-rules.mjs --print-gpu shows it), delete the old text, then rerun.`);
  return applyBlock(text, wanted, GPU_START, GPU_END, 'test-speedup GPU marker');
}

const lineOf = (text, at) => text.slice(0, at).split('\n').length;
const sep = (text) => (text === '' ? '' : text.endsWith('\n\n') ? '' : text.endsWith('\n') ? '\n' : '\n\n');

// Replaces the line that carries LINE_MARK, or appends the line. Returns the new text.
export function applyLine(text, wanted) {
  const at = text.indexOf(LINE_MARK);
  if (at === -1) return text + sep(text) + wanted;
  const again = text.indexOf(LINE_MARK, at + 1);
  if (again !== -1) throw new Error(`line ${lineOf(text, again)} repeats the test-speedup line. Fix: delete that line, then rerun.`);
  const s = text.lastIndexOf('\n', at) + 1;
  const nl = text.indexOf('\n', at);
  return text.slice(0, s) + wanted + (nl === -1 ? '' : text.slice(nl + 1));
}

// Replaces the marked section, or appends it after one blank line. Returns the new text.
export function applyBlock(text, wanted, start = START, end = END, label = 'test-speedup marker') {
  const s = text.indexOf(start);
  const e = text.indexOf(end);
  const extra = [text.indexOf(start, s + 1), text.indexOf(end, e + 1)].filter((i) => s !== -1 && e !== -1 && i !== -1);
  if (extra.length) throw new Error(`line ${lineOf(text, Math.min(...extra))} repeats a ${label}. Fix: delete that line, then rerun.`);
  if (s !== -1 && e > s) {
    let after = e + end.length;
    if (text[after] === '\n') after += 1;
    return text.slice(0, s) + wanted + text.slice(after);
  }
  if (s !== -1 || e !== -1) throw new Error(`line ${lineOf(text, s !== -1 ? s : e)} holds a ${label} without its pair. Fix: delete that line, then rerun.`);
  return text + sep(text) + wanted;
}

// CLAUDE.md that imports AGENTS.md already loads the line through it.
export function targets(root) {
  const out = [];
  if (existsSync(join(root, 'AGENTS.md'))) out.push('AGENTS.md');
  const claude = join(root, 'CLAUDE.md');
  if (existsSync(claude) && !/^\s*@(\.\/)?AGENTS\.md\s*$/m.test(readFileSync(claude, 'utf8'))) out.push('CLAUDE.md');
  return out;
}

function parse(argv) {
  const opts = { root: '.', doc: 'docs/testing.md', check: false, gpu: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') opts.check = true;
    else if (a === '--gpu') opts.gpu = true;
    else if (a === '--print-gpu') opts.printGpu = true;
    else if (a === '--gpu-helper' || a === '--gpu-guard') {
      if (!argv[i + 1] || argv[i + 1].startsWith('--')) throw new Error(`${a} needs a value`);
      opts[a === '--gpu-helper' ? 'helper' : 'guard'] = argv[++i];
    } else if (a === '--root' || a === '--doc') {
      if (!argv[i + 1] || argv[i + 1].startsWith('--')) throw new Error(`${a} needs a value`);
      opts[a.slice(2)] = argv[++i];
    } else if (a === '--help' || a === '-h') opts.help = true;
    else throw new Error(`unknown argument ${a}`);
  }
  if ((opts.gpu || opts.printGpu) && !(opts.helper && opts.guard)) throw new Error('--gpu needs --gpu-helper NAME and --gpu-guard CMD (the launch helper and the guard command the rule names)');
  return opts;
}

export function main(argv) {
  let opts;
  try { opts = parse(argv); } catch (err) { console.error(`agent-rules: ${err.message}\n${USAGE}`); return 2; }
  if (opts.help) { console.log(USAGE); return 0; }
  if (opts.printGpu) { process.stdout.write(gpuBlock(opts.helper, opts.guard)); return 0; }
  const root = resolve(opts.root);
  const files = targets(root);
  if (files.length === 0) {
    const why = existsSync(join(root, 'CLAUDE.md')) ? 'CLAUDE.md imports @AGENTS.md, which does not exist' : 'no AGENTS.md or CLAUDE.md';
    console.error(`agent-rules: ${why} in ${root}. Ask the owner which file the project's agents load, create it, then rerun.`);
    return 2;
  }
  const self = relative(process.cwd(), fileURLToPath(import.meta.url)) || 'agent-rules.mjs';
  const q = (v) => `'${v.replace(/'/g, "'\\''")}'`;
  const fix = `node ${self} --root ${opts.root}${opts.doc === 'docs/testing.md' ? '' : ` --doc ${opts.doc}`}${opts.gpu ? ` --gpu --gpu-helper ${q(opts.helper)} --gpu-guard ${q(opts.guard)}` : ''}`;
  const jobs = [
    { file: opts.doc, what: 'testing rules section', apply: applyBlock, wanted: block(), mark: START, init: '# Testing\n' },
    ...files.map((file) => ({ file, what: 'testing rules line', apply: applyLine, wanted: line(opts.doc), mark: LINE_MARK, init: '' })),
    ...(opts.gpu ? files.map((file) => ({
      file, what: 'GPU rule block', apply: (t, w) => applyGpu(t, w, gpuText(opts.helper, opts.guard)), wanted: gpuBlock(opts.helper, opts.guard), mark: GPU_START, init: '',
    })) : []),
  ];
  // All or nothing: every job runs on the text the earlier jobs left, and files are written only
  // when no job failed, so a refused GPU rule leaves the testing line unwritten too.
  let failed = false;
  const texts = new Map();
  const lines = [];
  for (const { file, what, apply, wanted, mark, init } of jobs) {
    const path = join(root, file);
    const exists = texts.has(path) ? texts.get(path).exists : existsSync(path);
    const text = texts.has(path) ? texts.get(path).text : exists ? readFileSync(path, 'utf8') : init;
    let next;
    try { next = apply(text, wanted); } catch (err) { console.error(`${file}: ${err.message}`); failed = true; continue; }
    const state = exists && next === text ? 'unchanged' : text.includes(mark) ? 'updated' : 'added';
    if (opts.check) {
      if (state === 'unchanged') console.log(`${file}: ${what} current`);
      else { console.log(`${file}: ${what} ${state === 'added' ? 'missing' : 'stale'}. Fix: ${fix}`); failed = true; }
    } else {
      texts.set(path, { exists: exists || state !== 'unchanged', text: next, changed: (texts.get(path)?.changed ?? false) || state !== 'unchanged' });
      lines.push(`${file}: ${what} ${state}`);
    }
  }
  if (opts.check) return failed ? 1 : 0;
  if (failed) { console.error('agent-rules: nothing written; fix the error above and rerun.'); return 1; }
  for (const [path, { text, changed }] of texts) if (changed) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text); }
  for (const l of lines) console.log(l);
  return 0;
}

// realpath: on macOS a temp or copied folder under /var is /private/var to import.meta.url, and a plain
// resolve() would make the script exit 0 with no output.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
